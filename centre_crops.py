"""Turn dish_boxes.json into crops.json: a 4:3 crop centred on each dish that keeps "avoid" items out.

A crop of the same fraction in width and height keeps the 4:3 shape. Start with a margin around the
dish; if that would take in an avoided item, shift the centre a little and then shrink the margin
(down to trimming the plate rim) until it doesn't. Run crop_images.py afterwards.
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent
MARGIN = 0.06       # space kept around the dish on its longer side
MIN_MARGIN = -0.07  # most we'll trim into the plate edge to dodge an item
SHIFTS = [0.0, 0.02, -0.02, 0.04, -0.04, 0.06, -0.06]


def place(cx, cy, s):
    s = min(s, 1.0)
    l = min(max(cx - s / 2, 0.0), 1.0 - s)
    t = min(max(cy - s / 2, 0.0), 1.0 - s)
    return [l, t, l + s, t + s]


def overlap(a, b):
    w = min(a[2], b[2]) - max(a[0], b[0])
    h = min(a[3], b[3]) - max(a[1], b[1])
    return w * h if w > 0 and h > 0 else 0.0


def best_crop(dish, avoid):
    cx, cy = (dish[0] + dish[2]) / 2, (dish[1] + dish[3]) / 2
    side = max(dish[2] - dish[0], dish[3] - dish[1])
    margin = MARGIN
    while margin >= MIN_MARGIN - 1e-9:
        for dx in SHIFTS:
            for dy in SHIFTS:
                box = place(cx + dx, cy + dy, side + 2 * margin)
                if not any(overlap(box, a) for a in avoid):
                    return box, margin, (dx, dy)
        margin -= 0.01
    box = min((place(cx, cy, side + 2 * m / 100) for m in range(int(MIN_MARGIN * 100), int(MARGIN * 100) + 1)),
              key=lambda b: sum(overlap(b, a) for a in avoid))
    return box, None, (0, 0)


boxes = {k: v for k, v in json.loads((ROOT / "dish_boxes.json").read_text(encoding="utf-8")).items() if not k.startswith("_")}
crops = {"_note": "Generated by centre_crops.py from dish_boxes.json - edit that file, not this one. Applied by crop_images.py."}
for dish, info in boxes.items():
    if "crop" in info:
        crops[dish] = info["crop"]
        print(f"manual {dish}")
        continue
    box, margin, shift = best_crop(info["dish"], info.get("avoid", []))
    crops[dish] = [round(v, 3) for v in box]
    if margin is None:
        print(f"WARN {dish}: could not fully avoid an item")
    elif margin < MARGIN or shift != (0, 0):
        print(f"note {dish}: margin {margin:+.2f}, shift {shift}")
(ROOT / "crops.json").write_text(json.dumps(crops, indent=2) + "\n", encoding="utf-8")
print(f"{len(boxes)} crops written")
